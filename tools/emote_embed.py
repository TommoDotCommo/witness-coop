#!/usr/bin/env python3
"""Embed assets/emotes/*.emote into proxy/model/emote_data.h (the proxy carries its clips; no file I/O at load).
Usage: python3 tools/emote_embed.py [--check]    --check: exit 1 when the header is out of date (T0 gate)."""
from pathlib import Path
import sys
root = Path(__file__).resolve().parent.parent
src = sorted((root / 'assets/emotes').glob('*.emote'))
text = ''.join('# ---- %s\n%s\n' % (p.name, p.read_text()) for p in src)
assert ')EMOTE"' not in text
chunks = [text[i:i + 12000] for i in range(0, len(text), 12000)] or ['']      # split: compilers cap one literal's length
body = '\n'.join('R"EMOTE(%s)EMOTE"' % c for c in chunks)
out = ('#pragma once\n// Generated by tools/emote_embed.py from assets/emotes/*.emote. Do not edit: edit the clips and re-run it.\n'
       'namespace wm {\ninline constexpr const char* kEmoteClipText =\n%s;\n}\n' % body)
dst = root / 'proxy/model/emote_data.h'
if '--check' in sys.argv:
    if not dst.exists() or dst.read_text() != out: sys.exit('proxy/model/emote_data.h is out of date: run python3 tools/emote_embed.py')
    print('emote_data.h up to date (%d clips)' % len(src)); sys.exit(0)
dst.write_text(out); print('%s: %d clips, %d bytes' % (dst.relative_to(root), len(src), len(text)))
